const enTranslations = Object.entries(arTranslations).reduce<
  Record<string, string>
>((acc, [en, ar]) => {
  if (!acc[ar]) acc[ar] = en;
  return acc;
}, {});

export function translateText(text: string, language: AppLanguage) {
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const normalized = text.trim().replace(/\s+/g, " ");
  const translated =
    language === "ar"
      ? (arTranslations[normalized] ?? translateDynamicText(normalized, "ar"))
      : (enTranslations[normalized] ?? translateDynamicText(normalized, "en"));

  if (!translated || translated === normalized) return text;

  return `${leading}${translated}${trailing}`;
}

function translateDynamicText(
  text: string,
  targetLanguage: AppLanguage,
): string {
  if (text.includes(" · ")) {
    return text
      .split(" · ")
      .map((part) => translateText(part, targetLanguage))
      .join(" · ");
  }

  if (targetLanguage === "ar") {
    const prefixedValue = text.match(
      /^(Branch|Warehouse|Category|Product): (.+)$/,
    );
    if (prefixedValue) {
      const labels: Record<string, string> = {
        Branch: "الفرع",
        Warehouse: "المخزن",
        Category: "التصنيف",
        Product: "المنتج",
      };
      return `${labels[prefixedValue[1] ?? ""] ?? prefixedValue[1]}: ${prefixedValue[2]}`;
    }

    const countMatch = text.match(/^Count (.+)$/);
    if (countMatch) return `جرد ${countMatch[1]}`;

    const coverageMatch = text.match(/^(\d+) coverage months$/);
    if (coverageMatch) return `تغطية ${coverageMatch[1]} شهر`;

    const settingsDestinationMatch = text.match(/^Settings · (.+)$/);
    if (settingsDestinationMatch) {
      const label = settingsDestinationMatch[1] ?? "";
      return `إعدادات · ${arTranslations[label] ?? label}`;
    }

    const ordersMatch = text.match(/^(\d+)\s+orders?$/);
    if (ordersMatch) return `${ordersMatch[1]} طلب`;

    const lineMatch = text.match(/^(\d+)\s+lines?$/);
    if (lineMatch) return `${lineMatch[1]} بند`;

    const addedMatch = text.match(/^Added\s+(.+)$/);
    if (addedMatch) return `تمت إضافة ${addedMatch[1]}`;

    const normalizedEnum = text.replaceAll("_", " ").toLowerCase();
    const enumTranslations: Record<string, string> = {
      approved: "معتمد",
      cancelled: "ملغي",
      card: "كارت",
      cash: "نقدي",
      cashier: "كاشير",
      closed: "مغلقة",
      completed: "مكتمل",
      credit: "آجل",
      damaged: "تالف",
      draft: "مسودة",
      expired: "منتهي الصلاحية",
      finished: "منتج نهائي",
      ingredient: "مكوّن",
      inventory: "أمين مخزن",
      invoiced: "تمت فوترته",
      manager: "مدير",
      open: "مفتوح",
      other: "أخرى",
      owner: "مالك",
      paid: "مدفوع",
      pending: "قيد الانتظار",
      wallet: "محفظة",
      preparing: "جاري التحضير",
      received: "مستلم",
      refunded: "مسترد",
      reopened: "أعيد فتحه",
      sent: "مرسل",
      spillage: "انسكاب",
      submitted: "مرسل",
      transfer_in: "تحويل وارد",
      transfer_out: "تحويل صادر",
      voided: "ملغي",
    };
    if (enumTranslations[normalizedEnum])
      return enumTranslations[normalizedEnum];

    const sessionMatch = text.match(/^Session: (.+)$/);
    if (sessionMatch) return `الجلسة: ${sessionMatch[1]}`;

    const cashierMatch = text.match(/^Cashier: (.+)$/);
    if (cashierMatch) return `الكاشير: ${cashierMatch[1]}`;

    const cannotOpenMatch = text.match(/^(.+) cannot open (.+)\\.$/);
    if (cannotOpenMatch)
      return `${cannotOpenMatch[1]} لا يمكنه فتح ${cannotOpenMatch[2]}.`;

    const cashierDeniedMatch = text.match(
      /^Your cashier account cannot open (.+)\\. Ask a manager if you need help\\.$/,
    );
    if (cashierDeniedMatch) {
      return `حساب الكاشير لا يمكنه فتح ${translateDynamicText(
        cashierDeniedMatch[1] ?? "",
        "ar",
      )}. اطلب مساعدة المدير لو محتاج.`;
    }

    const inventoryDeniedMatch = text.match(
      /^Inventory staff cannot open (.+)\\. Use Products and Inventory from the menu\\.$/,
    );
    if (inventoryDeniedMatch) {
      return `فريق المخزون لا يمكنه فتح ${translateDynamicText(
        inventoryDeniedMatch[1] ?? "",
        "ar",
      )}. استخدم المنتجات والمخزون من المنيو.`;
    }

    const permissionDeniedMatch = text.match(
      /^You do not have permission to open (.+)\\.$/,
    );
    if (permissionDeniedMatch) {
      return `ليس لديك صلاحية لفتح ${translateDynamicText(
        permissionDeniedMatch[1] ?? "",
        "ar",
      )}.`;
    }
  } else {
    const prefixedValue = text.match(/^(فرع|مخزن|تصنيف|قسم|منتج): (.+)$/);
    if (prefixedValue) {
      const labels: Record<string, string> = {
        فرع: "Branch",
        مخزن: "Warehouse",
        تصنيف: "Category",
        قسم: "Category",
        منتج: "Product",
      };
      return `${labels[prefixedValue[1] ?? ""] ?? prefixedValue[1]}: ${prefixedValue[2]}`;
    }

    const arabicLineMatch = text.match(/^(\d+)\s+بند$/);
    if (arabicLineMatch) return `${arabicLineMatch[1]} lines`;

    const arabicAddedMatch = text.match(/^تمت إضافة\s+(.+)$/);
    if (arabicAddedMatch) return `Added ${arabicAddedMatch[1]}`;

    const sessionMatch = text.match(/^الجلسة:\s+(.+)$/);
    if (sessionMatch) return `Session: ${sessionMatch[1]}`;

    const cashierMatch = text.match(/^الكاشير:\s+(.+)$/);
    if (cashierMatch) return `Cashier: ${cashierMatch[1]}`;
  }

  return text;
}
